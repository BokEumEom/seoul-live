// 인스타그램 딥링크 조립. 지도 앱 링크(`mapLinks.ts`)와 같은 이유로 도메인에
// 둔다 — 네트워크도 SDK도 쓰지 않는 순수 계산이고, 실제로 여는 것은
// `platform/links.ts`의 `openExternalUrl`이 맡는다.

/**
 * 해시태그에 쓸 수 있는 글자. 인스타그램은 한글·라틴 문자·숫자·밑줄만 받는다.
 * 자모(ㄱ-ㅎ, ㅏ-ㅣ)까지 넣은 것은 완성형이 아닌 이름이 카탈로그에 들어와도
 * 조용히 통째로 지워지지 않게 하려는 것이다.
 */
const NOT_TAGGABLE = /[^0-9A-Za-z가-힣ㄱ-ㅎㅏ-ㅣ_]/g

/** 「(2호선)」처럼 이름 뒤에 붙는 괄호 설명. */
const PARENTHESISED = /\([^)]*\)/g

/**
 * 명소 이름을 사람들이 실제로 쓰는 해시태그로 줄인다.
 *
 * **카탈로그 이름을 그대로 쓸 수 없다.** 30곳 중 9곳에 해시태그가 못 받는
 * 글자가 들어 있다 — 괄호(`홍대입구역(2호선)`), 가운뎃점(`광화문·덕수궁`),
 * 공백(`명동 관광특구`). 그대로 인코딩해 보내면 태그가 없는 페이지로 간다.
 *
 * 세 단계를 이 순서로 밟는다. **순서가 뜻을 바꾼다.**
 *
 * 1. **괄호를 통째로 지운다.** `광장(전통)시장` → `광장시장`. 여는 괄호에서
 *    자르면 `광장`이 되어 다른 장소가 된다 — 남는 쪽도 이름의 일부다.
 * 2. **가운뎃점 앞만 남긴다.** `광화문·덕수궁` → `광화문`. 점을 지우기만 하면
 *    `광화문덕수궁`이라는 아무도 안 쓰는 태그가 된다. 두 이름을 잇는 기호라
 *    앞의 하나를 고르는 것이 맞다.
 * 3. **「관광특구」 꼬리를 뗀다.** 서울시의 행정 지정 명칭이지 사람들이 사진에
 *    다는 말이 아니다 — `#명동`과 `#명동관광특구`는 규모가 몇 자릿수 다르다.
 *    괄호와 같은 부류로 본다: 장소를 가리키는 말이 아니라 장소에 붙은 설명.
 *
 * 남는 글자가 없으면 빈 문자열이다. 부르는 쪽이 버튼을 안 그리는 신호다 —
 * 지금 카탈로그 30곳은 전부 값이 나오지만, 이름이 늘 때 조용히 깨진 링크가
 * 생기는 것보다 버튼이 없는 편이 낫다.
 */
export function instagramTag(name: string): string {
  const stripped = name
    .replace(PARENTHESISED, '')
    .split('·')[0]
    .replace(/\s*관광특구\s*$/, '')
  return stripped.replace(NOT_TAGGABLE, '')
}

/**
 * 그 명소의 인스타그램 태그 페이지.
 *
 * **`/explore/search/`가 아니라 `/explore/tags/`다.** 검색 주소는 로그인
 * 화면으로 튕기고(2026-08-19 실측: 302 → `/accounts/login/`), 태그 주소는
 * 로그인 없이도 200으로 열린다(`/popular/<태그>/`로 301된다). 미니앱에서 나가는
 * 링크라 받는 쪽 상태를 우리가 못 정하는데, 로그인부터 요구하면 대부분에게
 * 아무것도 안 보인다.
 *
 * 태그를 못 만들면 빈 문자열이다.
 */
export function instagramTagUrl(name: string): string {
  const tag = instagramTag(name)
  if (tag === '') {
    return ''
  }
  return `https://www.instagram.com/explore/tags/${encodeURIComponent(tag)}/`
}
